  // ------------------------------------------------- Grid -> Canvas-Frames --

  function buildCanvas(rows, pal, name) {
    const w = rows[0].length;
    const h = rows.length;
    const cv = document.createElement('canvas');
    cv.width = w; cv.height = h;
    const ctx = cv.getContext('2d');
    for (let y = 0; y < h; y++) {
      if (rows[y].length !== w) {
        throw new Error(`Sprite "${name}", row ${y}: ${rows[y].length} instead of ${w} chars`);
      }
      for (let x = 0; x < w; x++) {
        const ch = rows[y][x];
        if (ch === '.') continue;
        const col = pal[ch];
        if (!col) throw new Error(`Sprite "${name}": unknown character "${ch}" in row ${y}`);
        ctx.fillStyle = col;
        ctx.fillRect(x, y, 1, 1);
      }
    }
    return cv;
  }

  function flipCanvas(cv) {
    const out = document.createElement('canvas');
    out.width = cv.width; out.height = cv.height;
    const ctx = out.getContext('2d');
    ctx.translate(cv.width, 0);
    ctx.scale(-1, 1);
    ctx.drawImage(cv, 0, 0);
    return out;
  }

  function bottomRow(rows) {
    for (let y = rows.length - 1; y >= 0; y--) {
      if (/[^.]/.test(rows[y])) return y + 1;
    }
    return rows.length;
  }

  const frames = {};   // frames[char][skin][frame] = { right, left }
  const meta = {};     // meta[char][frame] = { w, h, bottom }

  function buildAll() {
    for (const charKey of Object.keys(CHARS)) {
      const char = CHARS[charKey];
      frames[charKey] = {};
      meta[charKey] = {};
      for (const name of Object.keys(char.grids)) {
        const rows = char.grids[name];
        meta[charKey][name] = { w: rows[0].length, h: rows.length, bottom: bottomRow(rows) };
      }
      for (const skinKey of Object.keys(SKINS[charKey])) {
        const skin = SKINS[charKey][skinKey];
        const palR = Object.assign({}, skin.colors, { E: skin.eyeR });
        const palL = Object.assign({}, skin.colors, { E: skin.eyeL });
        frames[charKey][skinKey] = {};
        for (const name of Object.keys(char.grids)) {
          const rows = char.grids[name];
          frames[charKey][skinKey][name] = {
            right: buildCanvas(rows, palR, `${charKey}:${name}`),
            left: flipCanvas(buildCanvas(rows, palL, `${charKey}:${name}`)),
          };
        }
      }
    }
  }

  // draw a frame at a world position (x = foot center, y = foot line)
  function draw(ctx, charKey, skinKey, frameName, facing, x, y, dy) {
    const f = frames[charKey][skinKey][frameName];
    const m = meta[charKey][frameName];
    const S = CHARS[charKey].scale;
    const img = facing >= 0 ? f.right : f.left;
    const dx = Math.round(x - (m.w * S) / 2);
    const dyy = Math.round(y - m.bottom * S + (dy || 0));
    ctx.drawImage(img, dx, dyy, m.w * S, m.h * S);
  }

  function idleFrame(charKey) {
    return CHARS[charKey].anims.idle.seq[0][0];
  }

