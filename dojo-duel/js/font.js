// Tiny 3x5 arcade-style pixel font. Each glyph: 5 rows of 3 bits.
window.DD = window.DD || {};

(function () {
  const G = {
    'A': ['010','101','111','101','101'],
    'B': ['110','101','110','101','110'],
    'C': ['011','100','100','100','011'],
    'D': ['110','101','101','101','110'],
    'E': ['111','100','110','100','111'],
    'F': ['111','100','110','100','100'],
    'G': ['011','100','101','101','011'],
    'H': ['101','101','111','101','101'],
    'I': ['111','010','010','010','111'],
    'J': ['001','001','001','101','010'],
    'K': ['101','101','110','101','101'],
    'L': ['100','100','100','100','111'],
    'M': ['101','111','111','101','101'],
    'N': ['110','101','101','101','101'],
    'O': ['010','101','101','101','010'],
    'P': ['110','101','110','100','100'],
    'Q': ['010','101','101','010','001'],
    'R': ['110','101','110','101','101'],
    'S': ['011','100','010','001','110'],
    'T': ['111','010','010','010','010'],
    'U': ['101','101','101','101','111'],
    'V': ['101','101','101','101','010'],
    'W': ['101','101','111','111','101'],
    'X': ['101','101','010','101','101'],
    'Y': ['101','101','010','010','010'],
    'Z': ['111','001','010','100','111'],
    '0': ['111','101','101','101','111'],
    '1': ['010','110','010','010','111'],
    '2': ['111','001','111','100','111'],
    '3': ['111','001','111','001','111'],
    '4': ['101','101','111','001','001'],
    '5': ['111','100','111','001','111'],
    '6': ['111','100','111','101','111'],
    '7': ['111','001','001','010','010'],
    '8': ['111','101','111','101','111'],
    '9': ['111','101','111','001','111'],
    '!': ['010','010','010','000','010'],
    '.': ['000','000','000','000','010'],
    ':': ['000','010','000','010','000'],
    '-': ['000','000','111','000','000'],
    '+': ['000','010','111','010','000'],
    '=': ['000','111','000','111','000'],
    '?': ['110','001','010','000','010'],
    '>': ['100','010','001','010','100'],
    '/': ['001','001','010','100','100'],
    ' ': ['000','000','000','000','000'],
  };

  // draw text; align: 'left' | 'center' | 'right'
  function drawText(ctx, text, x, y, scale, color, align) {
    text = String(text).toUpperCase();
    const w = text.length * 4 * scale - scale; // 3px glyph + 1px spacing
    if (align === 'center') x -= Math.floor(w / 2);
    if (align === 'right') x -= w;
    ctx.fillStyle = color;
    let cx = x;
    for (const ch of text) {
      const g = G[ch] || G['?'];
      for (let r = 0; r < 5; r++) {
        for (let c = 0; c < 3; c++) {
          if (g[r][c] === '1') {
            ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
          }
        }
      }
      cx += 4 * scale;
    }
  }

  // text with a black drop shadow – the HUD default
  function drawTextShadow(ctx, text, x, y, scale, color, align) {
    drawText(ctx, text, x + scale, y + scale, scale, '#000000', align);
    drawText(ctx, text, x, y, scale, color, align);
  }

  DD.font = { drawText, drawTextShadow };
})();
